// Builds the engine and copies the viewer page and the bridge types into the app (docs/design/00-architecture.md).
// Run after every change in engine/ (and in a fresh clone if setup.sh was not run).
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const engineRoot = join(appRoot, '..', 'engine');
const outDir = join(appRoot, 'src', 'viewer', 'generated');

execFileSync('npm', ['run', 'build'], { cwd: engineRoot, stdio: 'inherit' });

const html = readFileSync(join(engineRoot, 'dist', 'viewer.html'), 'utf8');
const bridge = readFileSync(join(engineRoot, 'src', 'bridge', 'bridge-messages.ts'), 'utf8');

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'viewer-html.ts'), `export const viewerHtml = ${JSON.stringify(html)};\n`);
writeFileSync(
  join(outDir, 'bridge-messages.ts'),
  `// Generated by npm run engine:sync from engine/src/bridge/bridge-messages.ts; don't edit.\n${bridge}`,
);
console.log(`engine:sync: wrote ${(html.length / 1024).toFixed(0)} KB viewer page and the bridge types to ${outDir}`);
